def load_env():
    env = {}
    with open(os.path.join(PROJECT_ROOT, ".env"), encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    return env


def load_topics():
    with open(os.path.join(PROJECT_ROOT, "app", "topics.json"), encoding="utf-8") as f:
        return json.load(f)


ENV = load_env()
